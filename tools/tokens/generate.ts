import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

import { parseCornerValues, parseFloatTokens, springEasing } from './tokens.ts';

/**
 * Compose Multiplatform's build of androidx material3 1.5.0-alpha17; its sources jar is on Maven Central, androidx's is
 * not. reference/compose/build.gradle.kts renders with that androidx version, so both move together. An alpha because
 * the Expressive API is internal in every stable material3 release so far.
 */
const COMPOSE_MATERIAL3 = '1.11.0-alpha07';
const OUTPUT = 'projects/expressive-angular/src/foundations/_tokens.scss';
const SPRINGS = ['FastSpatial', 'DefaultSpatial', 'SlowSpatial', 'FastEffects', 'DefaultEffects', 'SlowEffects'];

function kebab(name: string): string {
  return name.replace(/([a-z])([A-Z])/g, '$1-$2').toLowerCase();
}

async function readTokenSources(): Promise<{ motion: string; shape: string }> {
  const url =
    `https://repo1.maven.org/maven2/org/jetbrains/compose/material3/material3/${COMPOSE_MATERIAL3}/` +
    `material3-${COMPOSE_MATERIAL3}-sources.jar`;
  const response = await fetch(url);
  if (!response.ok) {
    throw new Error(`${url} answered ${response.status}`);
  }
  const dir = mkdtempSync(join(tmpdir(), 'compose-material3-'));
  const jar = join(dir, 'sources.jar');
  writeFileSync(jar, Buffer.from(await response.arrayBuffer()));
  const tokens = 'commonMain/androidx/compose/material3/tokens';
  execFileSync('unzip', ['-q', jar, `${tokens}/ExpressiveMotionTokens.kt`, `${tokens}/ShapeTokens.kt`, '-d', dir]);
  return {
    motion: readFileSync(join(dir, tokens, 'ExpressiveMotionTokens.kt'), 'utf8'),
    shape: readFileSync(join(dir, tokens, 'ShapeTokens.kt'), 'utf8'),
  };
}

function render(motion: string, shape: string): string {
  const springs = parseFloatTokens(motion);
  const lines = SPRINGS.flatMap((name) => {
    const damping = springs[`Spring${name}Damping`];
    const stiffness = springs[`Spring${name}Stiffness`];
    if (damping === undefined || stiffness === undefined) {
      throw new Error(`ExpressiveMotionTokens has no Spring${name}Damping/Stiffness`);
    }
    const { points, durationMs } = springEasing({ damping, stiffness });
    return [
      `  --exp-motion-${kebab(name)}: linear(${points.join(', ')});`,
      `  --exp-motion-${kebab(name)}-duration: ${durationMs}ms;`,
    ];
  });
  const corners = Object.entries(parseCornerValues(shape)).map(
    ([name, dp]) => `  --exp-corner-${kebab(name)}: ${dp}px;`
  );
  return [
    `// Generated by tools/tokens/generate.ts from org.jetbrains.compose.material3:material3:${COMPOSE_MATERIAL3}`,
    '// (ExpressiveMotionTokens, ShapeTokens). Do not edit; run `npm run tokens`.',
    '@mixin tokens {',
    ...lines,
    ...corners,
    '}',
    '',
  ].join('\n');
}

const { motion, shape } = await readTokenSources();
const scss = render(motion, shape);

if (process.argv.includes('--check')) {
  if (readFileSync(OUTPUT, 'utf8') !== scss) {
    console.error(`${OUTPUT} is stale. Run \`npm run tokens\` and commit the result.`);
    process.exit(1);
  }
} else {
  writeFileSync(OUTPUT, scss);
}

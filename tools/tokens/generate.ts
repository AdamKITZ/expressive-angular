import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

import { parseColorScheme, parseCornerValues, parseFloatTokens, springEasing } from './tokens.ts';

/**
 * Compose Multiplatform's build of androidx material3 1.5.0-alpha17; its sources jar is on Maven Central, androidx's is
 * not. reference/compose/build.gradle.kts renders with that androidx version, so both move together. An alpha because
 * the Expressive API is internal in every stable material3 release so far.
 */
const COMPOSE_MATERIAL3 = '1.11.0-alpha07';
const TOKENS_OUTPUT = 'projects/expressive-angular/src/foundations/_tokens.scss';
const SCHEME_OUTPUT = 'projects/showcase/src/reference/_compose-light-scheme.scss';
const SPRINGS = ['FastSpatial', 'DefaultSpatial', 'SlowSpatial', 'FastEffects', 'DefaultEffects', 'SlowEffects'];
const SOURCES = ['ExpressiveMotionTokens', 'ShapeTokens', 'ColorLightTokens', 'PaletteTokens'] as const;

type Sources = Record<(typeof SOURCES)[number], string>;

function kebab(name: string): string {
  return name.replace(/([a-z])([A-Z])/g, '$1-$2').toLowerCase();
}

async function readTokenSources(): Promise<Sources> {
  const url =
    `https://repo1.maven.org/maven2/org/jetbrains/compose/material3/material3/${COMPOSE_MATERIAL3}/` +
    `material3-${COMPOSE_MATERIAL3}-sources.jar`;
  const response = await fetch(url);
  if (!response.ok) {
    throw new Error(`${url} answered ${response.status}`);
  }
  const dir = mkdtempSync(join(tmpdir(), 'compose-material3-'));
  const jar = join(dir, 'sources.jar');
  writeFileSync(jar, Buffer.from(await response.arrayBuffer()));
  const tokens = 'commonMain/androidx/compose/material3/tokens';
  execFileSync('unzip', ['-q', jar, ...SOURCES.map((name) => `${tokens}/${name}.kt`), '-d', dir]);
  return Object.fromEntries(
    SOURCES.map((name) => [name, readFileSync(join(dir, tokens, `${name}.kt`), 'utf8')])
  ) as Sources;
}

function header(sources: string): string {
  return [
    `// Generated by tools/tokens/generate.ts from org.jetbrains.compose.material3:material3:${COMPOSE_MATERIAL3}`,
    `// (${sources}). Do not edit; run \`npm run tokens\`.`,
  ].join('\n');
}

function renderTokens(sources: Sources): string {
  const springs = parseFloatTokens(sources.ExpressiveMotionTokens);
  const lines = SPRINGS.flatMap((name) => {
    const damping = springs[`Spring${name}Damping`];
    const stiffness = springs[`Spring${name}Stiffness`];
    if (damping === undefined || stiffness === undefined) {
      throw new Error(`ExpressiveMotionTokens has no Spring${name}Damping/Stiffness`);
    }
    const { points, durationMs } = springEasing({ damping, stiffness });
    return [
      `  --exp-motion-${kebab(name)}: linear(${points.join(', ')});`,
      `  --exp-motion-${kebab(name)}-duration: ${durationMs}ms;`,
    ];
  });
  const corners = Object.entries(parseCornerValues(sources.ShapeTokens)).map(
    ([name, dp]) => `  --exp-corner-${kebab(name)}: ${dp}px;`
  );
  return [header('ExpressiveMotionTokens, ShapeTokens'), '@mixin tokens {', ...lines, ...corners, '}', ''].join('\n');
}

/** Compose's default light colour scheme as Angular Material system tokens, so reference scenes share colours. */
function renderScheme(sources: Sources): string {
  const roles = Object.entries(parseColorScheme(sources.ColorLightTokens, sources.PaletteTokens)).map(
    ([role, color]) => `  --mat-sys-${kebab(role)}: ${color};`
  );
  return [header('ColorLightTokens, PaletteTokens'), '@mixin compose-light-scheme {', ...roles, '}', ''].join('\n');
}

const sources = await readTokenSources();
const outputs: Record<string, string> = {
  [TOKENS_OUTPUT]: renderTokens(sources),
  [SCHEME_OUTPUT]: renderScheme(sources),
};

for (const [path, content] of Object.entries(outputs)) {
  if (!process.argv.includes('--check')) {
    writeFileSync(path, content);
  } else if (readFileSync(path, 'utf8') !== content) {
    console.error(`${path} is stale. Run \`npm run tokens\` and commit the result.`);
    process.exitCode = 1;
  }
}
